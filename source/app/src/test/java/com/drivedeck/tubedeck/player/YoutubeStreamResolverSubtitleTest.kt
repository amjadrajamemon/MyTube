package com.drivedeck.tubedeck.player

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

class YoutubeStreamResolverSubtitleTest {
    @Test
    fun parsesManualAndAutomaticCaptionsAndPrefersVtt() {
        val root = JSONObject().apply {
            put(
                "subtitles",
                JSONObject().put(
                    "en",
                    JSONArray()
                        .put(JSONObject().put("ext", "ttml").put("url", "https://example.test/en.ttml").put("name", "English"))
                        .put(JSONObject().put("ext", "vtt").put("url", "https://example.test/en.vtt").put("name", "English"))
                )
            )
            put(
                "automatic_captions",
                JSONObject().put(
                    "ur",
                    JSONArray()
                        .put(JSONObject().put("ext", "json3").put("url", "https://example.test/ur.json3").put("name", "Urdu"))
                        .put(JSONObject().put("ext", "vtt").put("url", "https://example.test/ur.vtt").put("name", "Urdu"))
                )
            )
        }

        val subtitles = YoutubeStreamResolver.parseDownloadEngineSubtitles(root)

        assertEquals(2, subtitles.size)
        val english = subtitles.first { it.languageTag == "en" }
        assertEquals("https://example.test/en.vtt", english.url)
        assertEquals("text/vtt", english.mimeType)
        assertFalse(english.autoGenerated)

        val urdu = subtitles.first { it.languageTag == "ur" }
        assertEquals("https://example.test/ur.vtt", urdu.url)
        assertEquals("text/vtt", urdu.mimeType)
        assertTrue(urdu.autoGenerated)
    }

    @Test
    fun ignoresNonHttpsAndLiveChatCaptionEntries() {
        val root = JSONObject().apply {
            put(
                "subtitles",
                JSONObject()
                    .put("live_chat", JSONArray().put(JSONObject().put("ext", "vtt").put("url", "https://example.test/chat.vtt")))
                    .put("en", JSONArray().put(JSONObject().put("ext", "vtt").put("url", "http://example.test/insecure.vtt")))
            )
        }

        assertTrue(YoutubeStreamResolver.parseDownloadEngineSubtitles(root).isEmpty())
    }
}
